// Fills templates/*.template.md with numbers from round2_data.json and writes
// 01_Video_Pitch/narration_script.md and storyboard.md. Edit the templates, not the outputs.
const { ROOT, content, projected, show, fs, path } = require("./lib");

const WPM = 135;
const fields = Object.entries(content.pitch_fields).filter(([k]) => !k.startsWith("_"));
// Figures that are still projections are shown in [brackets] so nobody records them by mistake.
const ALWAYS_REAL = /^actual_figures_not_from_round2\./;
const value = (name, plain) => {
  const hit = fields.find(([k]) => k === name);
  if (!hit) throw new Error(`Template uses {{${name}}} but content.json pitch_fields has no "${name}"`);
  const v = show(hit[1]);
  return projected && !plain && !ALWAYS_REAL.test(hit[1]) ? `[${v}]` : v;
};
const fillTemplate = (t, extra = {}) =>
  t.replace(/\{\{(\w+)\}\}/g, (_, k) => (k in extra ? extra[k] : k.endsWith("_plain") ? value(k.replace(/_plain$/, ""), true) : value(k)));

// Count spoken words per beat: only the quoted (>) lines under each "## Beat" heading.
const countBeats = (md) => {
  const beats = [];
  const re = /^## (Beat \d+)[^\n]*\n([\s\S]*?)(?=^## |^---)/gm;
  let m;
  while ((m = re.exec(md))) {
    const spoken = m[2].split("\n").filter((l) => l.startsWith(">")).join(" ")
      .replace(/\*\*LILY:\*\*/g, "").replace(/[*\[\]>"“”]/g, " ");
    beats.push({ beat: m[1], words: (spoken.match(/[A-Za-z0-9.']+/g) || []).length });
  }
  return beats;
};

const statusLine = projected
  ? "Numbers in **[brackets]** are projections from `../round2_data.json`. Record Beat 4 last, after the survey closes, and read the real numbers."
  : "All numbers are the final survey results from `../round2_data.json`.";

const build = () => {
  const out = {};
  const tplDir = path.join(ROOT, "templates");
  const banner = (n) => `<!-- GENERATED from templates/${n}.template.md and round2_data.json. Do not edit this file; edit those and run "npm run build" in tools/. -->\n`;

  const scriptTpl = fs.readFileSync(path.join(tplDir, "narration_script.template.md"), "utf8");
  const first = fillTemplate(scriptTpl, { count_line: "", status_line: statusLine });
  const beats = countBeats(first);
  const total = beats.reduce((a, b) => a + b.words, 0);
  const secs = Math.round((total / WPM) * 60);
  const countLine = `Total below is ${total} words, about ${Math.floor(secs / 60)}:${String(secs % 60).padStart(2, "0")} at that pace.`;
  out["narration_script.md"] = banner("narration_script") + fillTemplate(scriptTpl, { count_line: countLine, status_line: statusLine });

  const sbTpl = fs.readFileSync(path.join(tplDir, "storyboard.template.md"), "utf8");
  out["storyboard.md"] = banner("storyboard") + fillTemplate(sbTpl, { status_line: statusLine });
  return { out, beats, total, secs };
};

module.exports = { build, WPM };

if (require.main === module) {
  const { out, beats, total, secs } = build();
  for (const [name, text] of Object.entries(out)) fs.writeFileSync(path.join(ROOT, "01_Video_Pitch", name), text);
  console.log(`Pitch written: narration_script.md, storyboard.md  [${projected ? "PROJECTED" : "ACTUAL"}]`);
  console.log("  " + beats.map((b) => `${b.beat}: ${b.words}w`).join("  ") + `  | total ${total} words, about ${secs}s`);
}
